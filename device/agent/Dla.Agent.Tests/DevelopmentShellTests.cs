using System.Reflection;

namespace Dla.Agent.Tests;

/// <summary>Looks at the real built program file and its code. It never starts the program.</summary>
public class DevelopmentShellTests
{
    private static string AgentExe => Path.Combine(AppContext.BaseDirectory, "Dla.Agent.exe");

    [Fact]
    public void The_program_is_a_no_console_windows_app()
    {
        // WinExe: the PE header's subsystem is "Windows GUI" (2), not "Windows console" (3)
        using var fs = File.OpenRead(AgentExe);
        using var reader = new BinaryReader(fs);
        fs.Position = 0x3C;
        fs.Position = reader.ReadInt32();                    // start of the PE header
        Assert.Equal(0x00004550u, reader.ReadUInt32());      // "PE\0\0"
        fs.Position += 20;                                   // skip the COFF header
        fs.Position += 68;                                   // offset of Subsystem inside the optional header
        Assert.Equal((ushort)2, reader.ReadUInt16());
    }

    [Fact]
    public void The_program_refers_to_nothing_that_could_track_store_or_send_data_out_of_this_pc()
    {
        // The only network piece is the loopback status link, which needs System.Net.Sockets (a plain socket on 127.0.0.1).
        // No web client, no web server library, no mail, no web sockets, no TLS, no database, no hooks, no registry.
        var agent = typeof(AgentHost).Assembly;
        var names = agent.GetReferencedAssemblies().Select(a => a.Name!).ToList();

        foreach (var banned in new[] { "System.Net.Http", "System.Net.HttpListener", "System.Net.WebClient", "System.Net.Mail", "System.Net.Requests",
                                       "System.Net.WebSockets", "System.Net.WebSockets.Client", "System.Net.Security", "System.Net.WebProxy" })
            Assert.DoesNotContain(banned, names);

        foreach (var name in names)
            foreach (var forbidden in new[] { "Sqlite", "Sql", "Onnx", "Registry", "Hooks", "AspNetCore" })
                Assert.DoesNotContain(forbidden, name, StringComparison.OrdinalIgnoreCase);

        Assert.Contains("System.Net.Sockets", names);   // the one allowed network piece
    }

    [Fact]
    public void The_program_uses_no_input_window_or_screen_apis()
    {
        var agent = typeof(AgentHost).Assembly;
        var forbidden = new[] { "SendKeys", "Clipboard", "Cursor", "MousePosition", "Keyboard", "SetWindowsHookEx", "GetForegroundWindow", "GetLastInputInfo", "CopyFromScreen" };
        var all = string.Join("\n", agent.GetTypes().SelectMany(t =>
            t.GetMembers(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly)
             .Select(m => $"{t.FullName}.{m.Name}")));
        foreach (var f in forbidden) Assert.DoesNotContain(f, all);
    }

    [Fact]
    public void The_classes_are_only_consent_start_up_tray_single_instance_and_status_link_pieces()
    {
        var names = typeof(AgentHost).Assembly.GetTypes()
            .Where(t => !t.Name.StartsWith('<') && !t.Name.Contains("DisplayClass")
                        && t.Namespace?.StartsWith("System.Text.RegularExpressions.Generated", StringComparison.Ordinal) != true)   // types made by [GeneratedRegex];ApplicationConfiguration is generated by the WinForms SDK
            .Select(t => t.Name).OrderBy(n => n, StringComparer.Ordinal).ToArray();
        Assert.Equal(
            new[] {"AgentApplicationContext", "AgentHost", "AgentLaunchResult", "AgentLauncher", "AgentLinkConfig", "AgentState", "AgentStatus",
             "AgentStartup", "AgentStatusProvider", "ApplicationConfiguration", "ConsentDecision", "ConsentForm", "ConsentStore", "ConsentText", "DefaultConsentGate", "ExitCleanup",
             "FileAgentLog", "FileConsentGate", "IAgentLink", "IAgentLog", "IConsentGate", "IExitSource", "IStatusSource", "ITray", "ITrayIcon", "LocalStatusLink", "OnboardingFlow",
             "OnboardingOutcome", "Program", "SingleInstance", "StatusAnswer", "SystemExitSource", "TrayController", "TrayIconFactory", "WinFormsTrayIcon" }.OrderBy(n => n, StringComparer.Ordinal).ToArray(),
            names);
    }
}
